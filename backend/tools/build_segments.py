"""Builds data/static/segments.json: the points where the collector samples TomTom flow.

Each target is snapped onto the current TomTom route geometry. Where the two directions run
on separate carriageways (motorways), each direction gets its own point; on ordinary roads
one point covers both.

Run from backend/:  .venv/Scripts/python -m tools.build_segments
"""
import asyncio
import json

from app.config import STATIC_DIR
from app.feeds import tomtom
from tools.build_count_stations import dist_m

# id, name, road, approximate [lon, lat] (snapped to the routes below)
TARGETS = [
    ("thionville_west", "Thionville west exit", "D", (6.110, 49.364)),
    ("a30_thionville", "A30 west of Thionville", "A30", (6.083, 49.380)),
    ("a30_havange", "A30 near Havange", "A30", (6.041, 49.381)),
    ("a30_tressange", "A30 near Tressange", "A30", (5.985, 49.392)),
    ("a30_aumetz", "A30 Aumetz exit (PR 23)", "A30", (5.951, 49.395)),
    ("aumetz_village", "Aumetz village", "D", (5.9425, 49.4177)),
    ("aumetz_audun", "Aumetz → Audun road", "D", (5.949, 49.438)),
    ("audun_crossing", "Audun-le-Tiche crossing", "D", (5.957, 49.473)),
    ("micheville", "Micheville link", "D", (5.958, 49.489)),
    ("belval_access", "Belval access", "LU", (5.946, 49.499)),
    ("a31_terville", "A31 Terville", "A31", (6.132, 49.350)),
    ("a31_kanfen", "A31 Kanfen", "A31", (6.118, 49.4417)),
    ("a3_bettembourg", "A3 Croix de Bettembourg", "A3", (6.117, 49.4969)),
    ("a13_lankelz", "A13 Lankelz", "A13", (5.976, 49.5126)),
]
MAX_SNAP_M = 400
SAME_ROAD_M = 12  # closer than this: both directions on the same carriageway


def nearest(points, xy):
    best = min(points, key=lambda p: dist_m(p, xy))
    return best, dist_m(best, xy)


async def main():
    routes = {}
    for d in tomtom.DIRECTIONS:
        res = await tomtom.corridors_now(d)
        routes[d] = {r["id"]: [tuple(p) for p in r["points"]] for r in res["results"] if r.get("points")}
    segments = []
    for sid, name, road, xy in TARGETS:
        per_dir = {}
        for d, by_route in routes.items():
            cands = [(nearest(pts, xy), rid) for rid, pts in by_route.items()]
            (p, dist), _ = min(cands, key=lambda c: c[0][1])
            if dist <= MAX_SNAP_M:
                per_dir[d] = (p, sorted(rid for (q, dd), rid in cands if dd <= MAX_SNAP_M))
        if not per_dir:
            print(f"skip {sid}: no route within {MAX_SNAP_M} m")
            continue
        pts = list(per_dir.values())
        if len(pts) == 2 and dist_m(pts[0][0], pts[1][0]) > SAME_ROAD_M:
            for d, (p, rids) in per_dir.items():
                segments.append({"id": f"{sid}:{d}", "name": name, "road": road, "direction": d,
                                 "lon": round(p[0], 6), "lat": round(p[1], 6), "routes": rids})
        else:
            p, rids = pts[0]
            segments.append({"id": sid, "name": name, "road": road, "direction": "both",
                             "lon": round(p[0], 6), "lat": round(p[1], 6), "routes": rids})
    out = {"_doc": "Generated by backend/tools/build_segments.py - points where TomTom flow is sampled. "
                   "Ids must stay stable: they key the recorded history.", "segments": segments}
    (STATIC_DIR / "segments.json").write_text(json.dumps(out, ensure_ascii=False, indent=1), encoding="utf-8")
    for s in segments:
        print(s["id"].ljust(28), s["road"].ljust(4), s["routes"])
    print(len(segments), "segments")


if __name__ == "__main__":
    asyncio.run(main())
